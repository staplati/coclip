let activeLanguage = "en";

export function resolveLanguage(preference = "en") {
  return preference === "zh-CN" ? "zh-CN" : "en";
}

export function setLanguage(language) {
  activeLanguage = resolveLanguage(language);
}

export function t(key, variables = {}) {
  const template = messages[activeLanguage]?.[key] ?? messages.en[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) => String(variables[name] ?? ""));
}

export function applyTranslations(root = globalThis.document) {
  if (!root) return;
  const documentElement = root.documentElement || root.ownerDocument?.documentElement;
  if (documentElement) documentElement.lang = activeLanguage;

  for (const element of root.querySelectorAll?.("[data-i18n]") || []) {
    element.textContent = t(element.dataset.i18n);
  }
  for (const [attribute, selector] of [
    ["placeholder", "[data-i18n-placeholder]"],
    ["title", "[data-i18n-title]"],
    ["aria-label", "[data-i18n-aria-label]"],
    ["alt", "[data-i18n-alt]"]
  ]) {
    const dataName = `i18n${attribute.split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join("")}`;
    for (const element of root.querySelectorAll?.(selector) || []) {
      element.setAttribute(attribute, t(element.dataset[dataName]));
    }
  }
}
